# =============================================================================
# SECTION 27: PRACTICAL PERFORMANCE CONSIDERATIONS
# =============================================================================

"""
Asymptotic analysis is essential, but production performance depends on more
than the Master Theorem.

1. Constant factors

Theta(n log n) does not automatically mean one implementation is faster than
another Theta(n log n) implementation.

2. Memory allocation

Recursive algorithms may allocate temporary arrays or buffers.

3. Cache behavior

Memory-access patterns can strongly affect real performance.

4. Recursion overhead

Function calls and call-stack management have real costs.

5. Recursion depth

A theoretically logarithmic recursion depth is usually manageable, while
linear recursion can exceed language recursion limits.

6. Input distributions

Some algorithms have performance that depends on input structure.

7. Parallelism

Independent recursive subproblems can sometimes be processed concurrently,
although synchronization and communication introduce overhead.

8. Integer rounding

Actual subproblem sizes may differ by one because of floors and ceilings.

9. Base-case thresholds

Production implementations may stop recursion early and switch to a simpler
algorithm for small inputs.

Changing a constant-sized base threshold normally does not change the
asymptotic result, but it can significantly affect practical runtime.
"""


