# SECTION 8: CLASSICAL EXAMPLE - MERGE SORT
# =============================================================================

"""
Merge sort divides an array into two halves, recursively sorts both halves,
and merges them.

Recurrence:

    T(n) = 2T(n/2) + Theta(n)

Parameters:

    a = 2
    b = 2
    f(n) = n

Critical exponent:

    log_2(2) = 1

Therefore:

    n^(log_2(2)) = n

Because f(n) = Theta(n), this is Case 2:

    T(n) = Theta(n log n)
"""


def merge(left_values: list[int], right_values: list[int]) -> list[int]:
    """
    Merge two sorted lists.

    Time complexity:
        Theta(len(left_values) + len(right_values))
    """
    merged: list[int] = []
    left_index = 0
    right_index = 0

    while left_index < len(left_values) and right_index < len(right_values):
        if left_values[left_index] <= right_values[right_index]:
            merged.append(left_values[left_index])
            left_index += 1
        else:
            merged.append(right_values[right_index])
            right_index += 1

    merged.extend(left_values[left_index:])
    merged.extend(right_values[right_index:])

    return merged


def merge_sort(values: list[int]) -> list[int]:
    """
    Recursive merge sort.

    Time complexity:
        Theta(n log n)

    Auxiliary space:
        Theta(n) for merging, depending on implementation details.
    """
    if len(values) <= 1:
        return values.copy()

    middle = len(values) // 2

    left_half = merge_sort(values[:middle])
    right_half = merge_sort(values[middle:])

    return merge(left_half, right_half)


