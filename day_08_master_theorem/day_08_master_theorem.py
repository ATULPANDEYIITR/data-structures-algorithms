# SECTION 15: EMPIRICAL GROWTH COMPARISON
# =============================================================================

def compare_growth(
    recurrence_function: Callable[[int], float],
    theoretical_function: Callable[[int], float],
    input_sizes: list[int],
) -> list[tuple[int, float, float, float]]:
    """
    Compare a numerical recurrence with a theoretical asymptotic expression.

    The ratio:

        recurrence(n) / theoretical(n)

    does not need to converge to exactly 1.

    For Theta-equivalent functions, the ratio should generally remain bounded
    above and below by positive constants for sufficiently large n.
    """
    results = []

    for n in input_sizes:
        measured = recurrence_function(n)
        theoretical = theoretical_function(n)

        if theoretical == 0:
            ratio = float("inf")
        else:
            ratio = measured / theoretical

        results.append((n, measured, theoretical, ratio))

    return results


def print_growth_comparison(
    comparisons: list[tuple[int, float, float, float]]
) -> None:
    """
    Print recurrence and theoretical values.
    """
    print(
        f"{'n':<10}"
        f"{'Recurrence':<20}"
        f"{'Theory':<20}"
        f"{'Ratio':<15}"
    )

    for n, measured, theoretical, ratio in comparisons:
        print(
            f"{n:<10}"
            f"{measured:<20.4f}"
            f"{theoretical:<20.4f}"
            f"{ratio:<15.4f}"
        )


