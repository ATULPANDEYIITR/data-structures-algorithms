# SECTION 7: CLASSICAL EXAMPLE - BINARY SEARCH
# =============================================================================

"""
Binary search repeatedly discards approximately half of a sorted search space.

Recurrence:

    T(n) = T(n/2) + Theta(1)

Parameters:

    a = 1
    b = 2
    f(n) = 1

Critical exponent:

    log_2(1) = 0

Therefore:

    n^(log_2(1)) = n^0 = 1

The non-recursive work matches the critical function.

Case 2:

    T(n) = Theta(log n)
"""


def binary_search(sorted_values: list[int], target: int) -> int:
    """
    Iterative binary search.

    This implementation is included to connect the recurrence analysis with
    an actual algorithm.

    Time complexity:
        Theta(log n)

    Space complexity:
        Theta(1)
    """
    left = 0
    right = len(sorted_values) - 1

    while left <= right:
        middle = left + (right - left) // 2
        current = sorted_values[middle]

        if current == target:
            return middle

        if current < target:
            left = middle + 1
        else:
            right = middle - 1

    return -1


def recursive_binary_search(
    sorted_values: list[int],
    target: int,
    left: int = 0,
    right: Optional[int] = None,
) -> int:
    """
    Recursive binary search.

    The recursive call works on approximately half the previous range.

    A recursive implementation uses Theta(log n) call-stack space in the
    worst case.
    """
    if right is None:
        right = len(sorted_values) - 1

    if left > right:
        return -1

    middle = left + (right - left) // 2

    if sorted_values[middle] == target:
        return middle

    if sorted_values[middle] < target:
        return recursive_binary_search(
            sorted_values,
            target,
            middle + 1,
            right,
        )

    return recursive_binary_search(
        sorted_values,
        target,
        left,
        middle - 1,
    )


