@dataclass(frozen=True)
class PowerLogFunction:
    """
    Represents:

        f(n) = n^power * (log n)^log_power

    This representation handles many recurrence functions.

    Examples:

        Theta(1)
            power = 0, log_power = 0

        Theta(n)
            power = 1, log_power = 0

        Theta(n^2)
            power = 2, log_power = 0

        Theta(log n)
            power = 0, log_power = 1

        Theta(n log n)
            power = 1, log_power = 1

        Theta(n^2 log^3 n)
            power = 2, log_power = 3

    The exact logarithm base does not affect asymptotic classification when
    the base is a fixed constant greater than 1.
    """

    power: float
    log_power: float = 0.0

    def evaluate(self, n: float) -> float:
        """
        Numerically evaluate the represented function.

        log(max(n, 2)) avoids log(1) = 0 causing undefined behavior for
        negative logarithmic exponents in numerical demonstrations.
        """
        if n <= 0:
            raise ValueError("n must be positive.")

        safe_log = log(max(n, 2))
        return (n ** self.power) * (safe_log ** self.log_power)

    def describe(self) -> str:
        """Return a human-readable asymptotic description."""
        if self.power == 0 and self.log_power == 0:
            return "Theta(1)"

        parts = []

        if self.power != 0:
            if self.power == 1:
                parts.append("n")
            else:
                parts.append(f"n^{self.power:g}")

        if self.log_power != 0:
            if self.log_power == 1:
                parts.append("log n")
            else:
                parts.append(f"(log n)^{self.log_power:g}")

        return "Theta(" + " ".join(parts) + ")"


