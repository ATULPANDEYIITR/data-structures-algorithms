# SECTION 12: RECURSION TREE ANALYSIS
# =============================================================================

@dataclass
class RecursionLevel:
    """
    Represents one recursion-tree level.
    """

    level: int
    number_of_subproblems: float
    size_per_subproblem: float
    work_per_subproblem: float
    total_level_work: float


def build_recursion_tree(
    n: int,
    a: int,
    b: int,
    f: Callable[[float], float],
) -> list[RecursionLevel]:
    """
    Build a numerical recursion-tree representation.

    At level i:

        number of subproblems = a^i
        size of each subproblem = n / b^i

    Therefore:

        total work at level i = a^i * f(n / b^i)

    The tree stops when subproblem size reaches approximately 1.

    This numerical model is useful for observing why different Master Theorem
    cases arise.
    """
    if n < 1:
        raise ValueError("n must be at least 1.")
    if a < 1:
        raise ValueError("a must be at least 1.")
    if b <= 1:
        raise ValueError("b must be greater than 1.")

    levels: list[RecursionLevel] = []
    level = 0
    current_size = float(n)

    while current_size > 1:
        subproblem_count = float(a ** level)
        work_per_subproblem = f(current_size)
        total_work = subproblem_count * work_per_subproblem

        levels.append(
            RecursionLevel(
                level=level,
                number_of_subproblems=subproblem_count,
                size_per_subproblem=current_size,
                work_per_subproblem=work_per_subproblem,
                total_level_work=total_work,
            )
        )

        current_size /= b
        level += 1

    return levels


def print_recursion_tree(levels: list[RecursionLevel]) -> None:
    """
    Print a compact recursion-tree table.
    """
    print(
        f"{'Level':<8}"
        f"{'Subproblems':<15}"
        f"{'Size Each':<15}"
        f"{'Work Each':<15}"
        f"{'Total Level Work':<20}"
    )

    for node in levels:
        print(
            f"{node.level:<8}"
            f"{node.number_of_subproblems:<15.2f}"
            f"{node.size_per_subproblem:<15.2f}"
            f"{node.work_per_subproblem:<15.2f}"
            f"{node.total_level_work:<20.2f}"
        )


