"""
For Case 1:

    T(n) = 4T(n/2) + n

At level i:

    number of nodes = 4^i
    problem size = n/2^i
    work per node = n/2^i

Total level work:

    4^i * n/2^i
    = n * 2^i

The work increases toward the leaves.

For Case 2:

    T(n) = 2T(n/2) + n

At level i:

    number of nodes = 2^i
    work per node = n/2^i

Total level work:

    2^i * n/2^i
    = n

Every level performs Theta(n) work.

There are Theta(log n) levels.

Total:

    Theta(n log n)

For Case 3:

    T(n) = 2T(n/2) + n^2

At level i:

    total level work decreases geometrically:

        2^i * (n/2^i)^2
        = n^2 / 2^i

The root-level work dominates.

Total:

    Theta(n^2)
"""


# =============================================================================
# SECTION 14: NUMERICAL RECURRENCE SOLVER
# =============================================================================

def solve_recurrence_numerically(
    n: int,
    a: int,
    b: int,
    f: Callable[[int], float],
    base_cost: float = 1.0,
) -> float:
    """
    Numerically evaluate a recurrence:

        T(n) = aT(ceil(n/b)) + f(n)

    using memoization.

    Important distinction:
    The Master Theorem is asymptotic, while this function computes a concrete
    numerical recurrence for finite input sizes.

    Ceiling division handles input sizes that are not exact powers of b.
    """
    if n < 1:
        raise ValueError("n must be at least 1.")
    if a < 1:
        raise ValueError("a must be at least 1.")
    if b <= 1:
        raise ValueError("b must be greater than 1.")

    @lru_cache(maxsize=None)
    def recurrence(size: int) -> float:
        if size <= 1:
            return base_cost

        smaller_size = ceil(size / b)

        # Defensive guard against an invalid recursive reduction.
        if smaller_size >= size:
            raise RuntimeError("Recursive size did not decrease.")

        return a * recurrence(smaller_size) + f(size)

    return recurrence(n)


