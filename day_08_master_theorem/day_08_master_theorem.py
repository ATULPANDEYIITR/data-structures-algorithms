# SECTION 19: RECURRENCES THAT THE SIMPLE MASTER THEOREM DOES NOT HANDLE
# =============================================================================

"""
The standard Master Theorem does not apply directly to every recurrence.

EXAMPLE 1: Unequal subproblem sizes

    T(n) = T(n/3) + T(2n/3) + n

The recursive subproblems are not all the same size n/b.

The standard theorem requires a uniform subproblem size.

Possible approaches:
    - Recursion tree
    - Substitution
    - Akra-Bazzi theorem


EXAMPLE 2: Nonstandard reduction

    T(n) = T(n - 1) + n

The problem size decreases by subtraction rather than division.

This is not of the form n/b.

Expanding:

    T(n)
    = T(n-1) + n
    = T(n-2) + (n-1) + n
    = ...

The result is Theta(n^2).


EXAMPLE 3: Different subproblem counts

    T(n) = nT(n/2) + n

Here the number of recursive subproblems depends on n.

The standard theorem assumes constant a.


EXAMPLE 4: Problem-size-dependent division

    T(n) = 2T(n/log n) + n

The reduction factor is not a fixed constant b.


EXAMPLE 5: Oscillating or irregular f(n)

The regularity and polynomial separation assumptions can fail.

A recurrence may require direct expansion, bounding, or a more general theorem.
"""


# =============================================================================
# SECTION 20: UNEQUAL-SPLIT EXAMPLE
# =============================================================================

def unequal_split_cost(
    n: int,
    base_cost: float = 1.0,
) -> float:
    """
    Numerically evaluate:

        T(n) = T(floor(n/3)) + T(ceil(2n/3)) + n

    This is intentionally included as a recurrence that does NOT fit the
    simple Master Theorem.

    A guard ensures recursive sizes eventually decrease.
    """
    @lru_cache(maxsize=None)
    def recurrence(size: int) -> float:
        if size <= 1:
            return base_cost

        left_size = max(1, size // 3)
        right_size = max(1, (2 * size + 2) // 3)

        if right_size >= size:
            # For very small sizes, stop rather than create a non-decreasing call.
            return float(size)

        return (
            recurrence(left_size)
            + recurrence(right_size)
            + size
        )

    if n < 1:
        raise ValueError("n must be positive.")

    return recurrence(n)


# =============================================================================
# SECTION 21: SUBSTITUTION METHOD
# =============================================================================

"""
The substitution method solves a recurrence by:

1. Guessing an asymptotic bound.
2. Assuming the bound holds for smaller values.
3. Substituting that assumption into the recurrence.
4. Proving the resulting inequality.

Example:

    T(n) = 2T(n/2) + n

Guess:

    T(n) = O(n log n)

Assume:

    T(n/2) <= c(n/2)log(n/2)

Then:

    T(n)
    <= 2[c(n/2)log(n/2)] + n

    = cn(log n - 1) + n

    = cn log n - cn + n

For sufficiently large c, this can be bounded by:

    cn log n

A complete proof also needs base-case handling.

The substitution method is flexible and can solve many recurrences that are
not convenient for direct Master Theorem classification.
"""


# =============================================================================
# SECTION 22: ITERATION / EXPANSION METHOD
# =============================================================================

def expansion_terms_for_subtractive_recurrence(n: int) -> list[int]:
    """
    Return the non-recursive work terms for:

        T(n) = T(n-1) + n

    Expanding produces:

        n + (n-1) + ... + 2

    The sum is Theta(n^2).
    """
    if n < 1:
        raise ValueError("n must be positive.")

    return list(range(n, 1, -1))


def subtractive_recurrence_closed_form(n: int, base_cost: int = 1) -> int:
    """
    Compute the exact recurrence:

        T(1) = base_cost
        T(n) = T(n-1) + n

    The sum of integers gives:

        T(n) = base_cost + sum(k for k=2..n)

             = base_cost + n(n+1)/2 - 1

    This is Theta(n^2).
    """
    if n < 1:
        raise ValueError("n must be positive.")

    return base_cost + n * (n + 1) // 2 - 1


