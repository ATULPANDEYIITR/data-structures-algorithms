# SECTION 16: REGULARITY CONDITION
# =============================================================================

def check_regular_condition(
    a: float,
    b: float,
    f: Callable[[float], float],
    sample_sizes: list[int],
) -> list[tuple[int, float]]:
    """
    Numerically inspect the ratio:

        a f(n/b) / f(n)

    The Case 3 regularity condition requires that for sufficiently large n:

        a f(n/b) <= c f(n)

    for some constant c < 1.

    Therefore, if the sampled ratio remains below a value strictly smaller
    than 1 for large n, that supports the condition.

    This numerical function is not a mathematical proof. It is a diagnostic
    aid for understanding the condition.
    """
    if a < 1:
        raise ValueError("a must be at least 1.")
    if b <= 1:
        raise ValueError("b must be greater than 1.")

    ratios: list[tuple[int, float]] = []

    for n in sample_sizes:
        if n <= 1:
            continue

        numerator = a * f(n / b)
        denominator = f(n)

        if denominator == 0:
            ratio = float("inf")
        else:
            ratio = numerator / denominator

        ratios.append((n, ratio))

    return ratios


