# SECTION 6: AUTOMATIC CLASSIFICATION FOR POWER FUNCTIONS
# =============================================================================

@dataclass
class MasterTheoremResult:
    """
    Stores the classification of a recurrence.

    This implementation focuses on recurrences whose non-recursive work can
    be represented as:

        n^p (log n)^k

    Such forms cover many important algorithms and also demonstrate the
    generalized boundary behavior.
    """

    case_name: str
    critical_exponent: float
    recurrence_work: str
    non_recursive_work: str
    result: str
    explanation: str


def classify_power_log_recurrence(
    a: float,
    b: float,
    f: PowerLogFunction,
    tolerance: float = 1e-10,
) -> MasterTheoremResult:
    """
    Classify common recurrences of the form:

        T(n) = aT(n/b) + n^p (log n)^k

    The primary comparison is between p and:

        log_b(a)

    If p differs from the critical exponent, the standard Case 1 or Case 3
    comparison applies.

    If p equals the critical exponent, logarithmic factors determine the
    boundary behavior.

    Generalized boundary rule:

        T(n) = aT(n/b) + Theta(n^c log^k n)

    where c = log_b(a), and k >= 0:

        T(n) = Theta(n^c log^(k+1) n)

    The standard Case 2 corresponds to k = 0.

    For k < 0, the ordinary Master Theorem is not sufficient in its simplest
    textbook form. More advanced recurrence techniques may be required.
    """
    c = critical_exponent(a, b)

    if f.power < c - tolerance:
        return MasterTheoremResult(
            case_name="Case 1: Recursive work dominates",
            critical_exponent=c,
            recurrence_work=f"The recursive structure contributes Theta(n^{c:g}).",
            non_recursive_work=f.describe(),
            result=f"Theta(n^{c:g})",
            explanation=(
                "The polynomial exponent of f(n) is smaller than log_b(a), "
                "so the recursive subproblems dominate asymptotically."
            ),
        )

    if f.power > c + tolerance:
        return MasterTheoremResult(
            case_name="Case 3 candidate: Non-recursive work dominates",
            critical_exponent=c,
            recurrence_work=f"The recursive structure contributes Theta(n^{c:g}).",
            non_recursive_work=f.describe(),
            result=f"Theta({format_power_log(f)})",
            explanation=(
                "The polynomial exponent of f(n) is larger than log_b(a). "
                "Under the required regularity condition, f(n) dominates."
            ),
        )

    if f.log_power == 0:
        return MasterTheoremResult(
            case_name="Case 2: Balanced work",
            critical_exponent=c,
            recurrence_work=f"Theta(n^{c:g})",
            non_recursive_work=f.describe(),
            result=f"Theta(n^{c:g} log n)",
            explanation=(
                "The non-recursive work matches the critical polynomial "
                "growth rate, so each recursion level has comparable work."
            ),
        )

    if f.log_power > 0:
        return MasterTheoremResult(
            case_name="Generalized balanced logarithmic case",
            critical_exponent=c,
            recurrence_work=f"Theta(n^{c:g})",
            non_recursive_work=f.describe(),
            result=f"Theta(n^{c:g} (log n)^{f.log_power + 1:g})",
            explanation=(
                "The polynomial part matches the critical exponent and the "
                "existing logarithmic factor gains one additional power."
            ),
        )

    return MasterTheoremResult(
        case_name="Boundary case requiring additional analysis",
        critical_exponent=c,
        recurrence_work=f"Theta(n^{c:g})",
        non_recursive_work=f.describe(),
        result="Not classified by the simple three-case implementation",
        explanation=(
            "The polynomial exponents match, but f(n) contains a negative "
            "logarithmic power. This is a boundary form that may require "
            "Akra-Bazzi, recursion-tree summation, substitution, or another "
            "advanced technique."
        ),
    )


def format_power_log(f: PowerLogFunction) -> str:
    """
    Format the mathematical expression without the Theta wrapper.
    """
    if f.power == 0 and f.log_power == 0:
        return "1"

    components = []

    if f.power != 0:
        if f.power == 1:
            components.append("n")
        else:
            components.append(f"n^{f.power:g}")

    if f.log_power != 0:
        if f.log_power == 1:
            components.append("log n")
        else:
            components.append(f"(log n)^{f.log_power:g}")

    return " ".join(components)


