def validate_recursive_problem_reduction(
    n: int,
    b: int,
) -> list[int]:
    """
    Return the sequence of sizes produced by repeated ceiling division.

    This can help detect a recursion that fails to make progress.
    """
    if n < 1:
        raise ValueError("n must be positive.")
    if b <= 1:
        raise ValueError("b must be greater than 1.")

    sizes = [n]
    current = n

    while current > 1:
        next_size = ceil(current / b)

        if next_size >= current:
            raise RuntimeError(
                "The recursive problem size is not decreasing."
            )

        sizes.append(next_size)
        current = next_size

    return sizes


