# SECTION 24: COMMON MISTAKES
# =============================================================================

"""
COMMON MISTAKE 1:
Comparing f(n) with a instead of n^(log_b(a)).

Incorrect:
    "There are 2 subproblems, so compare f(n) with 2."

Correct:
    Compute:

        n^(log_b(a))


COMMON MISTAKE 2:
Forgetting that b is the division factor.

For:

    T(n) = 8T(n/2) + n^2

the critical exponent is:

    log_2(8) = 3

not log_8(2).


COMMON MISTAKE 3:
Treating every larger f(n) as Case 3.

Case 3 requires polynomial separation in the standard theorem and a
regularity condition.

Boundary functions can require more careful analysis.


COMMON MISTAKE 4:
Ignoring logarithmic factors when polynomial exponents are equal.

For:

    T(n) = 2T(n/2) + n log n

f(n) is not simply identical to n.

The generalized logarithmic boundary rule yields:

    Theta(n log^2 n)


COMMON MISTAKE 5:
Applying the theorem to unequal subproblem sizes.

The recurrence:

    T(n) = T(n/3) + T(2n/3) + n

does not match aT(n/b).


COMMON MISTAKE 6:
Ignoring base cases.

A recurrence is incomplete without termination conditions.


COMMON MISTAKE 7:
Confusing exact runtime with asymptotic runtime.

The Master Theorem provides asymptotic growth, not an exact operation count.
"""


