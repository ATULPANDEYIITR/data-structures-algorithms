-- Workflow query: identify validated snapshots and their node totals.
SELECT
    snapshot.snapshot_id,
    snapshot.tree_name,
    snapshot.status,
    COUNT(node.node_id) AS node_count
FROM tree_snapshot AS snapshot
LEFT JOIN tree_node AS node
    ON node.snapshot_id = snapshot.snapshot_id
WHERE snapshot.status = 'VALIDATED'
GROUP BY
    snapshot.snapshot_id,
    snapshot.tree_name,
    snapshot.status
ORDER BY snapshot.snapshot_id;


-- Balance eligibility: return only trees satisfying the balance rule.
SELECT
    snapshot.snapshot_id,
    snapshot.tree_name,
    metrics.max_depth,
    metrics.min_depth,
    metrics.diameter_edges,
    metrics.node_count
FROM tree_snapshot AS snapshot
CROSS JOIN LATERAL analyze_tree(
    snapshot.snapshot_id,
    0
) AS metrics
WHERE metrics.is_balanced
ORDER BY snapshot.snapshot_id;


