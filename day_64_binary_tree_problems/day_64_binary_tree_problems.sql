-- Binary Tree Problems: PostgreSQL relational implementation
-- Requires PostgreSQL 14 or later.
--
-- A tree snapshot stores a binary tree as relational node records.
-- Node references are scoped to a snapshot through composite foreign keys.
-- Deferred triggers validate the complete structure at transaction commit.

DROP SCHEMA IF EXISTS tree_lab CASCADE;
CREATE SCHEMA tree_lab;

SET search_path TO tree_lab, public;

-- A snapshot represents one independently maintained binary tree.
CREATE TABLE tree_snapshot (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tree_name TEXT NOT NULL UNIQUE,
    root_node_id BIGINT,
    status TEXT NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'VALIDATED', 'ARCHIVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Every node has a stable identifier within its snapshot.
-- Child identifiers reference nodes in the same snapshot.
CREATE TABLE tree_node (
    snapshot_id BIGINT NOT NULL,
    node_id BIGINT NOT NULL,
    node_value BIGINT NOT NULL,
    left_child_id BIGINT,
    right_child_id BIGINT,

    PRIMARY KEY (snapshot_id, node_id),

    CONSTRAINT fk_node_snapshot
        FOREIGN KEY (snapshot_id)
        REFERENCES tree_snapshot(snapshot_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_distinct_children
        CHECK (
            left_child_id IS NULL
            OR right_child_id IS NULL
            OR left_child_id <> right_child_id
        ),

    CONSTRAINT chk_not_own_child
        CHECK (
            (left_child_id IS NULL OR left_child_id <> node_id)
            AND
            (right_child_id IS NULL OR right_child_id <> node_id)
        ),

    CONSTRAINT fk_left_child
        FOREIGN KEY (snapshot_id, left_child_id)
        REFERENCES tree_node(snapshot_id, node_id)
        DEFERRABLE INITIALLY DEFERRED,

    CONSTRAINT fk_right_child
        FOREIGN KEY (snapshot_id, right_child_id)
        REFERENCES tree_node(snapshot_id, node_id)
        DEFERRABLE INITIALLY DEFERRED
);

-- The root is also a node belonging to the same snapshot.
-- Deferral allows the snapshot and its nodes to be inserted in one transaction.
ALTER TABLE tree_snapshot
ADD CONSTRAINT fk_snapshot_root
FOREIGN KEY (snapshot_id, root_node_id)
REFERENCES tree_node(snapshot_id, node_id)
DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX idx_tree_snapshot_status
    ON tree_snapshot(status);

CREATE INDEX idx_tree_node_left_child
    ON tree_node(snapshot_id, left_child_id)
    WHERE left_child_id IS NOT NULL;

CREATE INDEX idx_tree_node_right_child
    ON tree_node(snapshot_id, right_child_id)
    WHERE right_child_id IS NOT NULL;


-- Validate the structural properties of one stored tree.
--
-- Checks:
-- 1. An empty snapshot has no root.
-- 2. A non-empty snapshot has a root.
-- 3. No child is assigned to more than one parent.
-- 4. A reachable cycle does not exist.
-- 5. Every stored node is reachable from the root.
--
-- Composite foreign keys independently ensure that references remain
-- within the same snapshot.

CREATE OR REPLACE FUNCTION validate_tree_integrity(
    p_snapshot_id BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_root BIGINT;
    v_total BIGINT;
    v_reachable BIGINT;
    v_has_cycle BOOLEAN;
    v_duplicate_child BIGINT;
BEGIN
    SELECT root_node_id
    INTO v_root
    FROM tree_snapshot
    WHERE snapshot_id = p_snapshot_id;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COUNT(*)
    INTO v_total
    FROM tree_node
    WHERE snapshot_id = p_snapshot_id;

    IF v_total = 0 THEN
        IF v_root IS NOT NULL THEN
            RAISE EXCEPTION 'Empty snapshot % has a root.', p_snapshot_id
                USING ERRCODE = '23514';
        END IF;

        RETURN;
    END IF;

    IF v_root IS NULL THEN
        RAISE EXCEPTION 'Non-empty snapshot % has no root.', p_snapshot_id
            USING ERRCODE = '23514';
    END IF;

    -- A binary-tree child can have at most one incoming parent reference.
    SELECT child_id
    INTO v_duplicate_child
    FROM (
        SELECT left_child_id AS child_id
        FROM tree_node
        WHERE snapshot_id = p_snapshot_id
          AND left_child_id IS NOT NULL

        UNION ALL

        SELECT right_child_id AS child_id
        FROM tree_node
        WHERE snapshot_id = p_snapshot_id
          AND right_child_id IS NOT NULL
    ) AS child_references
    GROUP BY child_id
    HAVING COUNT(*) > 1
    LIMIT 1;

    IF v_duplicate_child IS NOT NULL THEN
        RAISE EXCEPTION
            'Node % has more than one parent in snapshot %.',
            v_duplicate_child,
            p_snapshot_id
            USING ERRCODE = '23514';
    END IF;

    -- The path prevents infinite recursion if a cycle is encountered.
    WITH RECURSIVE walk(node_id, path, is_cycle) AS (
        SELECT
            v_root,
            ARRAY[v_root]::BIGINT[],
            FALSE

        UNION ALL

        SELECT
            child.child_id,
            walk.path || child.child_id,
            child.child_id = ANY(walk.path)
        FROM walk
        JOIN tree_node AS parent
          ON parent.snapshot_id = p_snapshot_id
         AND parent.node_id = walk.node_id
        CROSS JOIN LATERAL (
            VALUES
                (parent.left_child_id),
                (parent.right_child_id)
        ) AS child(child_id)
        WHERE child.child_id IS NOT NULL
          AND NOT walk.is_cycle
    )
    SELECT
        COALESCE(BOOL_OR(is_cycle), FALSE),
        COUNT(DISTINCT node_id) FILTER (WHERE NOT is_cycle)
    INTO v_has_cycle, v_reachable
    FROM walk;

    IF v_has_cycle THEN
        RAISE EXCEPTION 'A cycle exists in snapshot %.', p_snapshot_id
            USING ERRCODE = '23514';
    END IF;

    IF v_reachable <> v_total THEN
        RAISE EXCEPTION
            'Snapshot % contains unreachable nodes. Reachable: %, stored: %.',
            p_snapshot_id,
            v_reachable,
            v_total
            USING ERRCODE = '23514';
    END IF;
END;
$$;


-- Deferred constraint triggers evaluate the final transaction state.
-- This allows child references and roots to be inserted before all
-- referenced rows have been created.

CREATE OR REPLACE FUNCTION validate_tree_change_trigger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_snapshot_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_snapshot_id := OLD.snapshot_id;
    ELSE
        v_snapshot_id := NEW.snapshot_id;
    END IF;

    PERFORM validate_tree_integrity(v_snapshot_id);

    IF TG_OP = 'UPDATE'
       AND TG_TABLE_NAME = 'tree_node'
       AND OLD.snapshot_id <> NEW.snapshot_id THEN
        PERFORM validate_tree_integrity(OLD.snapshot_id);
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_validate_tree_node
AFTER INSERT OR UPDATE OR DELETE ON tree_node
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_tree_change_trigger();

CREATE CONSTRAINT TRIGGER trg_validate_tree_snapshot
AFTER INSERT OR UPDATE OR DELETE ON tree_snapshot
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION validate_tree_change_trigger();


-- Publish only a structurally valid snapshot.
CREATE OR REPLACE PROCEDURE publish_tree(
    p_snapshot_id BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM validate_tree_integrity(p_snapshot_id);

    UPDATE tree_snapshot
    SET status = 'VALIDATED'
    WHERE snapshot_id = p_snapshot_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Snapshot % does not exist.', p_snapshot_id;
    END IF;
END;
$$;


-- Retrieve all main metrics for a tree.
--
-- Diameter is measured in edges.
-- Maximum and minimum depth are measured in nodes.
-- Balance is determined at every node using the difference between
-- its left and right subtree heights.
--
-- A recursive traversal produces node depths and path sums.
-- A reverse-depth pass calculates subtree heights, diameters,
-- and balance states using JSON objects keyed by node identifier.

CREATE OR REPLACE FUNCTION analyze_tree(
    p_snapshot_id BIGINT,
    p_target_sum BIGINT
)
RETURNS TABLE (
    max_depth INTEGER,
    min_depth INTEGER,
    has_path_sum BOOLEAN,
    diameter_edges INTEGER,
    is_balanced BOOLEAN,
    node_count BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_root BIGINT;
    v_total BIGINT;
    v_count BIGINT := 0;
    v_max_depth INTEGER := 0;
    v_min_depth INTEGER := NULL;
    v_diameter INTEGER := 0;
    v_balanced BOOLEAN := TRUE;
    v_has_path_sum BOOLEAN := FALSE;

    v_heights JSONB := '{}'::JSONB;
    v_balance_states JSONB := '{}'::JSONB;

    v_left_height INTEGER;
    v_right_height INTEGER;
    v_height INTEGER;

    v_left_balanced BOOLEAN;
    v_right_balanced BOOLEAN;

    rec RECORD;
BEGIN
    PERFORM validate_tree_integrity(p_snapshot_id);

    SELECT root_node_id
    INTO v_root
    FROM tree_snapshot
    WHERE snapshot_id = p_snapshot_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Snapshot % does not exist.', p_snapshot_id;
    END IF;

    SELECT COUNT(*)
    INTO v_total
    FROM tree_node
    WHERE snapshot_id = p_snapshot_id;

    IF v_total = 0 THEN
        RETURN QUERY
        SELECT 0, 0, FALSE, 0, TRUE, 0::BIGINT;
        RETURN;
    END IF;

    FOR rec IN
        WITH RECURSIVE walk(
            node_id,
            depth,
            running_sum,
            path
        ) AS (
            SELECT
                root.node_id,
                1,
                root.node_value,
                ARRAY[root.node_id]::BIGINT[]
            FROM tree_node AS root
            WHERE root.snapshot_id = p_snapshot_id
              AND root.node_id = v_root

            UNION ALL

            SELECT
                child.node_id,
                walk.depth + 1,
                walk.running_sum + child.node_value,
                walk.path || child.node_id
            FROM walk
            JOIN tree_node AS parent
              ON parent.snapshot_id = p_snapshot_id
             AND parent.node_id = walk.node_id
            CROSS JOIN LATERAL (
                VALUES
                    (parent.left_child_id),
                    (parent.right_child_id)
            ) AS child_reference(child_id)
            JOIN tree_node AS child
              ON child.snapshot_id = p_snapshot_id
             AND child.node_id = child_reference.child_id
            WHERE child_reference.child_id IS NOT NULL
              AND NOT (child_reference.child_id = ANY(walk.path))
        )
        SELECT
            walk.node_id,
            walk.depth,
            walk.running_sum,
            node.left_child_id,
            node.right_child_id
        FROM walk
        JOIN tree_node AS node
          ON node.snapshot_id = p_snapshot_id
         AND node.node_id = walk.node_id
        ORDER BY walk.depth DESC
    LOOP
        v_count := v_count + 1;
        v_max_depth := GREATEST(v_max_depth, rec.depth);

        -- Child heights have already been computed because this is
        -- a deepest-first traversal.
        v_left_height := COALESCE(
            (v_heights ->> (rec.left_child_id::TEXT))::INTEGER,
            0
        );

        v_right_height := COALESCE(
            (v_heights ->> (rec.right_child_id::TEXT))::INTEGER,
            0
        );

        v_height := 1 + GREATEST(
            v_left_height,
            v_right_height
        );

        v_heights := v_heights || JSONB_BUILD_OBJECT(
            rec.node_id::TEXT,
            v_height
        );

        v_left_balanced := COALESCE(
            (v_balance_states ->> (rec.left_child_id::TEXT))::BOOLEAN,
            TRUE
        );

        v_right_balanced := COALESCE(
            (v_balance_states ->> (rec.right_child_id::TEXT))::BOOLEAN,
            TRUE
        );

        v_balanced := (
            v_balanced
            AND v_left_balanced
            AND v_right_balanced
            AND ABS(v_left_height - v_right_height) <= 1
        );

        v_balance_states := v_balance_states || JSONB_BUILD_OBJECT(
            rec.node_id::TEXT,
            (
                v_left_balanced
                AND v_right_balanced
                AND ABS(v_left_height - v_right_height) <= 1
            )
        );

        v_diameter := GREATEST(
            v_diameter,
            v_left_height + v_right_height
        );

        IF rec.left_child_id IS NULL
           AND rec.right_child_id IS NULL THEN
            v_min_depth := CASE
                WHEN v_min_depth IS NULL THEN rec.depth
                ELSE LEAST(v_min_depth, rec.depth)
            END;

            IF rec.running_sum = p_target_sum THEN
                v_has_path_sum := TRUE;
            END IF;
        END IF;
    END LOOP;

    IF v_count <> v_total THEN
        RAISE EXCEPTION
            'Analysis found % reachable nodes out of % stored nodes.',
            v_count,
            v_total;
    END IF;

    RETURN QUERY
    SELECT
        v_max_depth,
        COALESCE(v_min_depth, 0),
        v_has_path_sum,
        v_diameter,
        v_balanced,
        v_count;
END;
$$;


-- General node counting is valid for any structurally valid binary tree.
CREATE OR REPLACE FUNCTION count_tree_nodes(
    p_snapshot_id BIGINT
)
RETURNS BIGINT
LANGUAGE sql
STABLE
AS $$
    SELECT COUNT(*)
    FROM tree_node
    WHERE snapshot_id = p_snapshot_id;
$$;


-- A complete binary tree has occupied heap positions from 1 through n
-- without gaps. This function verifies completeness before returning
-- the count. Verification requires O(n) traversal time.

CREATE OR REPLACE FUNCTION count_complete_tree_nodes(
    p_snapshot_id BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
AS $$
DECLARE
    v_root BIGINT;
    v_total BIGINT;
    v_position_count BIGINT;
    v_max_position NUMERIC;
BEGIN
    PERFORM validate_tree_integrity(p_snapshot_id);

    SELECT root_node_id
    INTO v_root
    FROM tree_snapshot
    WHERE snapshot_id = p_snapshot_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Snapshot % does not exist.', p_snapshot_id;
    END IF;

    SELECT COUNT(*)
    INTO v_total
    FROM tree_node
    WHERE snapshot_id = p_snapshot_id;

    IF v_total = 0 THEN
        RETURN 0;
    END IF;

    WITH RECURSIVE positions(
        node_id,
        heap_position,
        path
    ) AS (
        SELECT
            v_root,
            1::NUMERIC,
            ARRAY[v_root]::BIGINT[]

        UNION ALL

        SELECT
            child.node_id,
            child_reference.heap_position,
            positions.path || child.node_id
        FROM positions
        JOIN tree_node AS parent
          ON parent.snapshot_id = p_snapshot_id
         AND parent.node_id = positions.node_id
        CROSS JOIN LATERAL (
            VALUES
                (
                    parent.left_child_id,
                    positions.heap_position * 2
                ),
                (
                    parent.right_child_id,
                    positions.heap_position * 2 + 1
                )
        ) AS child_reference(node_id, heap_position)
        JOIN tree_node AS child
          ON child.snapshot_id = p_snapshot_id
         AND child.node_id = child_reference.node_id
        WHERE child_reference.node_id IS NOT NULL
          AND NOT (child_reference.node_id = ANY(positions.path))
    )
    SELECT
        COUNT(DISTINCT heap_position),
        MAX(heap_position)
    INTO v_position_count, v_max_position
    FROM positions;

    IF v_position_count <> v_total
       OR v_max_position <> v_total::NUMERIC THEN
        RAISE EXCEPTION
            'Snapshot % is not a complete binary tree.',
            p_snapshot_id
            USING ERRCODE = '23514';
    END IF;

    RETURN v_total;
END;
$$;


-- Reporting view for snapshot-level metrics that do not require
-- a target path sum.
CREATE OR REPLACE VIEW tree_snapshot_summary AS
SELECT
    snapshot.snapshot_id,
    snapshot.tree_name,
    snapshot.status,
    snapshot.root_node_id,
    COUNT(node.node_id) AS node_count,
    MIN(node.node_value) AS minimum_node_value,
    MAX(node.node_value) AS maximum_node_value,
    snapshot.created_at
FROM tree_snapshot AS snapshot
LEFT JOIN tree_node AS node
    ON node.snapshot_id = snapshot.snapshot_id
GROUP BY
    snapshot.snapshot_id,
    snapshot.tree_name,
    snapshot.status,
    snapshot.root_node_id,
    snapshot.created_at;


