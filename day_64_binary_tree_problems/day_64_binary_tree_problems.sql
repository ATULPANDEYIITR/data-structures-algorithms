-- Operational note:
-- Deferred row-level structural triggers revalidate affected snapshots
-- at transaction commit. This is appropriate for small learning datasets.
-- Large bulk-ingestion workflows should batch writes and account for
-- the cost of repeated validation. The analyze_tree function also uses
-- JSONB maps to retain intermediate subtree metrics; an application-side
-- postorder traversal is preferable for very large trees.
